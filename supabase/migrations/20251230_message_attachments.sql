-- ============================================
-- Create message_attachments table
-- ============================================

CREATE TABLE IF NOT EXISTS public.message_attachments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  message_id uuid NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  file_name text NOT NULL,
  file_url text NOT NULL,
  file_type text NOT NULL,
  file_size integer NOT NULL CHECK (file_size > 0 AND file_size <= 10485760), -- Max 10MB
  thumbnail_url text, -- For images, can be generated by Vercel Blob
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- ============================================
-- Comments
-- ============================================

COMMENT ON TABLE public.message_attachments IS
'File and photo attachments for chat messages. Max file size: 10MB. Supported types: images (jpg, png, gif, webp), documents (pdf, doc, docx, xls, xlsx), archives (zip)';

COMMENT ON COLUMN public.message_attachments.file_size IS
'File size in bytes. Maximum allowed: 10485760 (10MB)';

COMMENT ON COLUMN public.message_attachments.thumbnail_url IS
'Thumbnail URL for images. Can be auto-generated by Vercel Blob or manually set.';

-- ============================================
-- Indexes
-- ============================================

CREATE INDEX idx_message_attachments_message_id
ON public.message_attachments(message_id);

CREATE INDEX idx_message_attachments_created_at
ON public.message_attachments(created_at DESC);

-- ============================================
-- RLS Policies
-- ============================================

ALTER TABLE public.message_attachments ENABLE ROW LEVEL SECURITY;

-- Users can view attachments in chat rooms they participate in
CREATE POLICY "Users can view attachments in their chat rooms"
ON public.message_attachments
FOR SELECT
USING (
  EXISTS (
    SELECT 1 FROM messages m
    INNER JOIN chat_participants cp ON cp.chat_room_id = m.chat_room_id
    WHERE m.id = message_attachments.message_id
    AND cp.user_id = next_auth.uid()
  )
);

-- Authenticated users can upload attachments to messages in their chat rooms
CREATE POLICY "Users can upload attachments to their messages"
ON public.message_attachments
FOR INSERT
WITH CHECK (
  EXISTS (
    SELECT 1 FROM messages m
    INNER JOIN chat_participants cp ON cp.chat_room_id = m.chat_room_id
    WHERE m.id = message_attachments.message_id
    AND cp.user_id = next_auth.uid()
  )
);

-- Users can delete their own attachments
CREATE POLICY "Users can delete their own attachments"
ON public.message_attachments
FOR DELETE
USING (
  EXISTS (
    SELECT 1 FROM messages m
    WHERE m.id = message_attachments.message_id
    AND m.sender_id = next_auth.uid()
  )
);

