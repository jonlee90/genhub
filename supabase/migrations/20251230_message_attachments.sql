-- Auto-update updated_at timestamp
CREATE TRIGGER update_message_attachments_updated_at
BEFORE UPDATE ON public.message_attachments
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

-- Update message.updated_at when attachment is added/removed
CREATE OR REPLACE FUNCTION update_message_on_attachment_change()
RETURNS TRIGGER AS $$
BEGIN
  IF TG_OP = 'INSERT' OR TG_OP = 'UPDATE' THEN
    UPDATE messages SET updated_at = now() WHERE id = NEW.message_id;
  ELSIF TG_OP = 'DELETE' THEN
    UPDATE messages SET updated_at = now() WHERE id = OLD.message_id;
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER on_message_attachment_change
AFTER INSERT OR UPDATE OR DELETE ON public.message_attachments
FOR EACH ROW
EXECUTE FUNCTION update_message_on_attachment_change();

-- ============================================
-- Optional: Project attachment sync
-- ============================================

-- For project chat rooms, optionally sync attachments to the main attachments table
-- This allows project files uploaded via chat to appear in project file list
CREATE OR REPLACE FUNCTION sync_project_chat_attachments()
RETURNS TRIGGER AS $$
DECLARE
  v_project_id uuid;
BEGIN
  -- Only process INSERT operations
  IF TG_OP = 'INSERT' THEN
    -- Get project_id from chat_room if this is a project chat
    SELECT cr.project_id INTO v_project_id
    FROM messages m
    INNER JOIN chat_rooms cr ON cr.id = m.chat_room_id
    WHERE m.id = NEW.message_id
    AND cr.type = 'project'
    AND cr.project_id IS NOT NULL;

    -- If this is a project chat, create a corresponding attachments record
    IF v_project_id IS NOT NULL THEN
      INSERT INTO public.attachments (
        entity_type,
        entity_id,
        file_name,
        file_url,
        file_type,
        file_size,
        uploaded_by
      )
      SELECT
        'project'::attachment_entity_type,
        v_project_id,
        NEW.file_name,
        NEW.file_url,
        NEW.file_type,
        NEW.file_size,
        m.sender_id
      FROM messages m
      WHERE m.id = NEW.message_id
      ON CONFLICT DO NOTHING; -- Prevent duplicates if attachment already exists
    END IF;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

